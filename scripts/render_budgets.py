"""Writes benchmarks/render_budgets.txt from a render_perf JSON result.

    python scripts/render_budgets.py benchmarks/results/render_perf-<date>-<preset>-<config>-<gpu>.json

Only the production pipeline's scenes are budgeted; the reference renderer is
the ground truth for images, not a performance target.

- GPU entries (`<scene>.gpu`, `<scene>.gpu.<pass>`): the recorded mean plus
  the 5 % regression allowance of CLAUDE.md §10.7, with a 50 µs floor on the
  sub-0.2 ms entries so that timestamp jitter cannot fail them (as
  scripts/gpu_budgets.py). The p99 is reported, not budgeted: one scheduling
  hiccup moves it.
- CPU entries (`<scene>.cpu`): a flat 50 µs. The production path's frame
  costs the main thread a few microseconds whatever the object count (Phase
  10's exit criterion), so the budget exists to catch per-object work coming
  back, not to track noise.

Re-baselining (a new driver, a renderer change that moves the numbers on
purpose) is: run render_perf on the reference machine with --frames=240
--json, commit the JSON under benchmarks/results/, run this script, and state
the change in the PR (§10.7).
"""
import argparse
import json
import math
import os
import sys

ALLOWANCE = 0.05
FLOOR_NS = 50_000
FLOOR_BELOW_NS = 200_000
CPU_BUDGET_NS = 50_000


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("results", help="render_perf JSON output")
    parser.add_argument("--output", default=os.path.join("benchmarks", "render_budgets.txt"))
    args = parser.parse_args()

    with open(args.results, encoding="utf-8") as f:
        data = json.load(f)
    if data.get("executable") != "render_perf":
        print(f"{args.results}: not a render_perf result", file=sys.stderr)
        return 1

    lines = [
        "# Renderer budgets: maximum nanoseconds per frame for render_perf's",
        "# production scenes (docs/benchmarks.md \"Renderer runs\"), enforced by",
        "# .github/workflows/gpu-perf.yml on the self-hosted RTX 3060 Ti runner.",
        "# Generated by scripts/render_budgets.py from",
        f"# {os.path.basename(args.results)}:",
        "# GPU entries are the recorded mean plus the 5 % allowance of CLAUDE.md",
        "# §10.7 (50 µs floor below 0.2 ms); CPU entries are a flat 50 µs, which",
        "# per-object work on the main thread would break.",
        "",
    ]
    for entry in data["benchmarks"]:
        name = entry["name"]
        scene = name.split(".", 1)[0]
        if not scene.endswith("_production") or name.endswith(".p99"):
            continue
        if name.endswith(".cpu"):
            budget = CPU_BUDGET_NS
        else:
            mean = float(entry["ns_per_op"])
            budget = mean * (1.0 + ALLOWANCE)
            if mean < FLOOR_BELOW_NS:
                budget = max(budget, mean + FLOOR_NS)
        lines.append(f"{name:<46} {int(math.ceil(budget / 1000.0)) * 1000}")

    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
