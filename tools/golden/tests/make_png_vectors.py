"""Writes png_vectors.h, the zlib and PNG test vectors of test_png.c,
made with Python's zlib (Jean-loup Gailly and Mark Adler's reference
implementation) so our inflate is checked against an independent encoder:

    python tools/golden/tests/make_png_vectors.py > tools/golden/tests/png_vectors.h

The output is deterministic; rerun after changing this script and commit
both."""
import struct
import sys
import zlib


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    return f"static const u8 {name}[{len(data)}] = {{\n" + "\n".join(lines) + "\n};\n"


def compress(data, level, strategy=zlib.Z_DEFAULT_STRATEGY):
    c = zlib.compressobj(level, zlib.DEFLATED, 15, 9, strategy)
    return c.compress(data) + c.flush()


def chunk(kind, body):
    c = kind + body
    return struct.pack(">I", len(body)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)


def paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    return b if pb <= pc else c


def filter_rows(pixels, w, h, bpp, types):
    """Applies filter types[y] to row y (the encoder side of PNG §9)."""
    stride = w * bpp
    out = bytearray()
    prev = bytes(stride)
    for y in range(h):
        row = pixels[y * stride:(y + 1) * stride]
        t = types[y]
        out.append(t)
        for x in range(stride):
            a = row[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if t == 0:
                v = row[x]
            elif t == 1:
                v = row[x] - a
            elif t == 2:
                v = row[x] - b
            elif t == 3:
                v = row[x] - ((a + b) >> 1)
            else:
                v = row[x] - paeth(a, b, c)
            out.append(v & 0xFF)
        prev = row
    return bytes(out)


def png(w, h, color, bpp, pixels, types, level=9, interlace=0, depth=8):
    raw = filter_rows(pixels, w, h, bpp, types)
    ihdr = struct.pack(">IIBBBBB", w, h, depth, color, 0, 0, interlace)
    idat = compress(raw, level)
    # Split the IDAT stream in two chunks: decoders must concatenate.
    half = len(idat) // 2
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"tEXt", b"Comment\x00test") +
            chunk(b"IDAT", idat[:half]) + chunk(b"IDAT", idat[half:]) + chunk(b"IEND", b""))


def main():
    text = (b"Nepheline golden images: " * 6) + bytes(range(256)) + b"zzzzzzzzzzzzzzzzzzzz" * 3
    out = ["// SPDX-License-Identifier: Apache-2.0\n",
           "// Generated by tools/golden/tests/make_png_vectors.py with Python's zlib; do not\n",
           "// edit. See the comment above each array.\n#pragma once\n\n"]
    out.append(f"// The uncompressed payload of the zlib vectors: {len(text)} bytes.\n")
    out.append("#define ZLIB_PAYLOAD_SIZE %dU\n" % len(text))
    out.append("// zlib.compress(level 0): stored blocks.\n" + c_array("g_zlib_stored", compress(text, 0)))
    out.append("// strategy Z_FIXED: fixed Huffman codes.\n" +
               c_array("g_zlib_fixed", compress(text, 9, zlib.Z_FIXED)))
    # A skewed payload (mostly a few letters), for which dynamic codes win.
    seed = 12345
    skewed = bytearray()
    for _ in range(3000):
        seed = (seed * 1103515245 + 12345) & 0x7FFFFFFF
        r = (seed >> 16) % 100
        skewed.append(ord("e") if r < 40 else ord("t") if r < 65 else ord("a") if r < 80 else
                      ord(" ") if r < 92 else 33 + r)
    dyn = compress(bytes(skewed), 9)
    assert (dyn[2] >> 1) & 3 == 2, "the first block is not dynamic"
    assert (compress(text, 0)[2] >> 1) & 3 == 0
    assert (compress(text, 9, zlib.Z_FIXED)[2] >> 1) & 3 == 1
    crc = zlib.crc32(bytes(skewed))
    out.append("// The payload of g_zlib_dynamic: 3000 skewed bytes (an LCG over a few letters).\n")
    out.append("#define ZLIB_SKEWED_SIZE 3000U\n#define ZLIB_SKEWED_CRC 0x%08XU\n" % crc)
    out.append("// level 9 on the skewed payload: dynamic Huffman codes.\n" +
               c_array("g_zlib_dynamic", dyn))
    # A 5 x 5 RGBA image, one filter type per row (0..4), and greyscale +
    # alpha and greyscale versions of a 3 x 5 image.
    w, h = 5, 5
    rgba = b"".join(bytes(((x * 53 + y * 17) & 0xFF, (x * 7 + y * 91) & 0xFF, (x * y * 29) & 0xFF,
                           255 - x * 10)) for y in range(h) for x in range(w))
    out.append("// 5 x 5 RGBA, rows filtered with types 0, 1, 2, 3, 4; two IDAT chunks and a\n"
               "// tEXt chunk. Texel (x, y) = (53x + 17y, 7x + 91y, 29xy, 255 - 10x) mod 256.\n" +
               c_array("g_png_rgba_filters", png(w, h, 6, 4, rgba, [0, 1, 2, 3, 4])))
    ga = b"".join(bytes(((x * 40 + y * 9) & 0xFF, 200 - y * 30)) for y in range(5) for x in range(3))
    out.append("// 3 x 5 greyscale + alpha, filters 4 3 2 1 0. Texel = (40x + 9y, 200 - 30y).\n" +
               c_array("g_png_grey_alpha", png(3, 5, 4, 2, ga, [4, 3, 2, 1, 0])))
    g = bytes(((x * 40 + y * 9) & 0xFF) for y in range(5) for x in range(3))
    out.append("// 3 x 5 greyscale, filter 2. Texel = 40x + 9y.\n" +
               c_array("g_png_grey", png(3, 5, 0, 1, g, [2] * 5)))
    out.append("// The same 5 x 5 image declared 16-bit (unsupported).\n" +
               c_array("g_png_16bit", png(w, h, 6, 4, rgba, [0] * 5, depth=16)))
    out.append("// Declared interlaced (unsupported).\n" +
               c_array("g_png_interlaced", png(w, h, 6, 4, rgba, [0] * 5, interlace=1)))
    sys.stdout.buffer.write("".join(out).encode("ascii"))  # LF on every platform


main()
